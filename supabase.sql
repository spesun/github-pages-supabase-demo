create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  author text not null check (char_length(author) between 1 and 30),
  content text not null check (char_length(content) between 1 and 280),
  created_at timestamptz not null default now()
);

alter table public.messages enable row level security;

revoke all on table public.messages from anon, authenticated;
grant select, insert on table public.messages to anon, authenticated;
grant usage, select on sequence public.messages_id_seq to anon, authenticated;

drop policy if exists "Anyone can read messages" on public.messages;
create policy "Anyone can read messages"
on public.messages
for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can add messages" on public.messages;
create policy "Anyone can add messages"
on public.messages
for insert
to anon, authenticated
with check (
  char_length(trim(author)) between 1 and 30
  and char_length(trim(content)) between 1 and 280
);
