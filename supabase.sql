create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  author text not null check (char_length(author) between 1 and 30),
  content text not null check (char_length(content) between 1 and 280),
  user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

-- 兼容已经运行过旧版脚本的项目。
alter table public.messages
  add column if not exists user_id uuid references auth.users(id) on delete set null;

alter table public.messages enable row level security;

-- 所有人都可以读取；只有 authenticated 角色可以新增。
revoke all on table public.messages from anon, authenticated;
grant select on table public.messages to anon, authenticated;
grant insert on table public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

drop policy if exists "Anyone can read messages" on public.messages;
create policy "Anyone can read messages"
on public.messages
for select
to anon, authenticated
using (true);

-- 删除旧版允许匿名写入的策略。
drop policy if exists "Anyone can add messages" on public.messages;
drop policy if exists "Authenticated users can add messages" on public.messages;
create policy "Authenticated users can add messages"
on public.messages
for insert
to authenticated
with check (
  auth.uid() is not null
  and user_id = auth.uid()
  and char_length(trim(author)) between 1 and 30
  and char_length(trim(content)) between 1 and 280
);
